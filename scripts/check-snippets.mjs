#!/usr/bin/env node
// Type-check every ```lyra block on the site.
//
// The parse-level sweep this replaces caught stale syntax, but not meaning. Two real
// defects slipped past it: the data guide's introductory example redeclared the prelude's
// `Maybe` and shadowed it (lyra-W012), and its `match` example was written without `pure`
// and so tripped lyra-W018 — the guide teaching a style the compiler flags. Both parse
// perfectly. Only the type-checker sees them.
//
// Run: pnpm check:snippets

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { tmpdir } from "node:os";

const root = fileURLToPath(new URL("..", import.meta.url));
const docsDir = join(root, "src/content/docs");
const scratch = join(tmpdir(), "lyra-snippet-check.lyra");

// A block is skipped only for a reason that is written down.
//
// `reference/` is generated by `lyrac doc`, and its blocks are *signatures*: a declaration
// with no body is not a complete program, so it cannot type-check by construction. Any
// other exemption is per-block and must be opted into in the source with
// `<!-- lyra:no-check -->` immediately above the fence, which keeps the reason next to the
// code rather than in a list here that nobody revisits.
const SKIP_DIRS = ["reference"];
const SKIP_MARKER = "<!-- lyra:no-check -->";

function findCompiler() {
  const candidates = [
    process.env.LYRAC,
    join(root, "..", "lyra", "build", "lyrac"),
  ].filter(Boolean);
  for (const c of candidates) if (existsSync(c)) return c;
  const which = spawnSync("which", ["lyrac"], { encoding: "utf8" });
  if (which.status === 0) return which.stdout.trim();
  return null;
}

// Fail hard when the compiler is missing rather than reporting zero problems.
//
// A checker that skips its own subject is the failure this workspace has hit twice — the
// ASan suite that passed by skipping every test, and the Go build cache that served a
// stale parser. Both looked green.
const lyrac = findCompiler();
if (!lyrac) {
  console.error(
    "check-snippets: no lyrac found.\n" +
      "  Build it with `cd ../lyra && ./build.sh`, or set LYRAC to a binary.\n" +
      "  Refusing to report success without checking anything."
  );
  process.exit(2);
}

function check(source) {
  writeFileSync(scratch, source);
  const r = spawnSync(lyrac, ["check", scratch], { encoding: "utf8" });
  const out = ((r.stdout || "") + (r.stderr || "")).trim();
  return out ? out.split("\n") : [];
}

// Preflight: the standard library has to be reachable, or every snippet using `Maybe`
// fails and the report blames the docs for a broken toolchain. `lyrac` finds `std` beside
// its own executable, so a binary moved away from its `build/std` symlink checks nothing
// useful.
const preflight = check("let m: Maybe<i64> = None\n");
if (preflight.length > 0) {
  console.error(
    "check-snippets: the prelude is not reachable from " + lyrac + ":\n  " +
      preflight.join("\n  ") +
      "\n  `lyrac` resolves `std` beside its own executable — rebuild with ../lyra/build.sh."
  );
  process.exit(2);
}

function* markdownFiles(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) {
      if (SKIP_DIRS.includes(name)) continue;
      yield* markdownFiles(p);
    } else if (/\.mdx?$/.test(name)) {
      yield p;
    }
  }
}

let checked = 0;
let skipped = 0;
const failures = [];

for (const file of [...markdownFiles(docsDir)].sort()) {
  const text = readFileSync(file, "utf8");
  const re = /```lyra\n([\s\S]*?)```/g;
  let m;
  while ((m = re.exec(text)) !== null) {
    const line = text.slice(0, m.index).split("\n").length;
    // The marker sits on its own line directly above the fence.
    const before = text.slice(0, m.index).trimEnd();
    if (before.endsWith(SKIP_MARKER)) {
      skipped++;
      continue;
    }
    checked++;
    const problems = check(m[1]);
    if (problems.length > 0) {
      failures.push({ file: relative(root, file), line, problems });
    }
  }
}

for (const f of failures) {
  console.error(`\n${f.file}:${f.line}`);
  // The scratch path is noise in a report about a docs file.
  for (const p of f.problems) console.error("  " + p.replace(scratch + ":", ""));
}

const verdict = failures.length === 0 ? "ok" : `${failures.length} failing`;
console.log(
  `\nchecked ${checked} lyra snippets, skipped ${skipped} (marked or generated) — ${verdict}`
);
process.exit(failures.length === 0 ? 0 : 1);
